// Helper to determine Auspicious Day (ວັນດີຍາມດີ) based on traditional Lao astrology rules
export function getAuspiciousDayInfo(dateStr: string): AuspiciousDay {
  const parts = dateStr.split('-');
  const day = parseInt(parts[2], 10);
  const month = parseInt(parts[1], 10);
  const dow = new Date(dateStr + 'T00:00:00').getDay();

  // Pattern based on traditional Lao Tamra (ວັນທຸງໄຊ, ວັນອະທິບໍດີ, ວັນອຸດົມມົງຄຸນ)
  const score = (day * 3 + month * 5 + dow * 7) % 10;

  if (score === 1 || score === 5 || score === 8) {
    return {
      date: dateStr,
      rating: 'excellent',
      ratingNameLao: '⭐ ວັນທຸງໄຊ (ມື້ດີຍອດຢ້ຽມ)',
      suitableFor: ['ຂຶ້ນເຮືອນໃໝ່', 'ພິທີແຕ່ງດອງ', 'ອອກລົດໃໝ່', 'ເປີດຮ້ານຄ້າ/ເລີ່ມທຸລະກິດ', 'ບາສີສູ່ຂວັນ'],
      avoidFor: ['ການຜິດຖຽງກັນ', 'ເລື່ອນນັດໝາຍ'],
      goodHoursLao: 'ຍາມເຊົ້າ 09:09 - 10:45 ແລະ ຍາມບ່າຍ 13:19 - 15:30',
      elementLao: 'ທາດທອງ / ລົມໂຊກລາບ',
    };
  } else if (score === 2 || score === 6 || score === 9) {
    return {
      date: dateStr,
      rating: 'good',
      ratingNameLao: '✨ ວັນອະທິບໍດີ (ມື້ດີມີມຸງຄຸນ)',
      suitableFor: ['ເຮັດບຸນໃສ່ບາດ', 'ເດີນທາງໄກ', 'ເຊັນສັນຍາ', 'ປຸກເຮືອນ', 'ສອບເສັງ'],
      avoidFor: ['ການຕັດຕົ້ນໄມ້ໃຫຍ່'],
      goodHoursLao: '08:30 - 10:00 ແລະ 14:00 - 16:00',
      elementLao: 'ທາດນ້ຳ / ຄວາມຊຸ່ມເຢັນ',
    };
  } else if (score === 3 || score === 7) {
    return {
      date: dateStr,
      rating: 'neutral',
      ratingNameLao: '🌤️ ວັນປົກກະຕິ (ມື້ສະເໝີຕົວ)',
      suitableFor: ['ເຮັດວຽກປະຈຳວັນ', 'ຊື້ເຄື່ອງທົ່ວໄປ', 'ພັກຜ່ອນຢູ່ເຮືອນ'],
      avoidFor: ['ງານມົງຄຸນໃຫຍ່ທີ່ສຳຄັນຫຼາຍ'],
      goodHoursLao: '10:00 - 11:30',
      elementLao: 'ທາດດິນ / ຄວາມໝັ້ນຄົງ',
    };
  } else {
    return {
      date: dateStr,
      rating: 'caution',
      ratingNameLao: '⚠️ ວັນອຸບາດ / ຄວນລະວັງ (ມື້ບໍ່ຄວນເຮັດການໃຫຍ່)',
      suitableFor: ['ສວດມົນໄຫວ້ພະ', 'ປ່ອຍສັດປ່ອຍປາ', 'ທຳຄວາມສະອາດເຮືອນ'],
      avoidFor: ['ແຕ່ງດອງ', 'ຂຶ້ນເຮືອນໃໝ່', 'ອອກລົດໃໝ່', 'ລົງທຶນໃຫຍ່'],
      goodHoursLao: 'ຍາມເຊົ້າກ່ອນທ່ຽງ 07:00 - 08:30',
      elementLao: 'ທາດໄຟ / ຄວນໃຈເຢັນ',
    };
  }
}

