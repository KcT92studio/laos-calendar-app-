export function getThemeById(id: ThemeId): ColorTheme {
  return LAO_COLOR_THEMES.find((t) => t.id === id) || LAO_COLOR_THEMES[0];
}

export function getActiveThemeConfig(id: ThemeId, isDark: boolean): ActiveThemeConfig {
  const theme = getThemeById(id);
  const colors = isDark ? theme.dark : theme.light;

  return {
    id: theme.id,
    nameLao: theme.nameLao,
    nameEn: theme.nameEn,
    descriptionLao: theme.descriptionLao,
    isDark,
    colors,
    headerGradient: colors.headerGradient,
    headerBorder: colors.headerBorder,
    accentBarGradient: colors.accentBarGradient,
    pageBgClass: isDark ? 'bg-slate-900 text-slate-100' : 'bg-slate-50 text-slate-900',
    primaryColor: theme.primaryColor,
    secondaryColor: theme.secondaryColor,
  };
}

export function getThemeCssVariables(colors: ThemeColors): Record<string, string> {
  return {
    '--app-bg': colors.pageBg,
    '--card-bg': colors.cardBg,
    '--card-subtle-bg': colors.cardSubtleBg,
    '--card-border': colors.cardBorder,
    '--text-primary': colors.textPrimary,
    '--text-secondary': colors.textSecondary,
    '--text-muted': colors.textMuted,
    '--accent-primary': colors.primary,
    '--accent-secondary': colors.secondary,
    '--btn-primary-bg': colors.btnPrimaryBg,
    '--btn-primary-text': colors.btnPrimaryText,
    '--today-bg': colors.todayBg,
    '--today-text': colors.todayText,
    '--today-ring': colors.todayRing,
    '--holiday-color': colors.holidayColor,
    '--holiday-bg': colors.holidayBg,
    '--holiday-border': colors.holidayBorder,
    '--wan-sin-color': colors.wanSinColor,
    '--pattern-color': colors.patternColor,
  };
}
